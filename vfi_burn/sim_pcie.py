"""Simulated PCIe BAR0 MMIO bus, HAL transaction tracer, and simulated GA100 adapter.

Provides:
  - ``PCIeTransaction``: immutable record of one 32-bit BAR0 MMIO read/write
  - ``TracingMMIOBus``: ``MMIOBus`` decorator recording every PCIe BAR0 access generated by the HAL
  - ``SimulatedGA100PCIe``: register-accurate GA100 BAR0 + OTP + PCI config-space simulator
  - ``SimulatedGA100Adapter``: ``FuseReader`` + ``FuseWriter`` executing the real
    ``GA100FuseController`` HAL over ``SimulatedGA100PCIe`` (so simulated runs exercise
    the exact same fuse-request -> PCIe-BAR0 transaction sequence as live hardware)
  - ``trace_hal_program_sequence``: runs the real HAL on an ephemeral simulated PCIe bus
    to obtain the exact ordered PCIe BAR0 MMIO transactions for programming a row
"""

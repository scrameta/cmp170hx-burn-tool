@dataclass(frozen=True)
class PCIeTransaction:
    """One aligned 32-bit BAR0 PCIe MMIO transaction."""

    op: str  # "RD32" or "WR32"
    offset: int
    value: int
    reg_name: str = ""


class TracingMMIOBus(MMIOBus):
    """Transparent ``MMIOBus`` wrapper recording every BAR0 RD32/WR32 generated by the HAL."""

    def __init__(self, inner: MMIOBus) -> None:
        self._inner = inner
        self.transactions: list[PCIeTransaction] = []

    def read32(self, offset: int) -> int:
        value = self._inner.read32(offset)
        self.transactions.append(
            PCIeTransaction(
                op="RD32",
                offset=offset,
                value=value,
                reg_name=register_name_for_address(offset),
            )
        )
        return value

    def write32(self, offset: int, value: int, *, allow_debugctrl: bool = False) -> None:
        self._inner.write32(offset, value, allow_debugctrl=allow_debugctrl)
        self.transactions.append(
            PCIeTransaction(
                op="WR32",
                offset=offset,
                value=value & 0xFFFFFFFF,
                reg_name=register_name_for_address(offset),
            )
        )

    def writes(self) -> list[PCIeTransaction]:
        return [tx for tx in self.transactions if tx.op == "WR32"]

    def reads(self) -> list[PCIeTransaction]:
        return [tx for tx in self.transactions if tx.op == "RD32"]

    def clear(self) -> None:
        self.transactions.clear()


def build_pcie_config_space(*, lnkcap2: int = 0x06, vendor: int = 0x10DE, device: int = 0x20C2) -> bytes:
    """Build a synthetic 256-byte PCIe config space with PCIe Cap ID 0x10 and ``LnkCap2``."""
    cfg = bytearray(256)
    struct.pack_into("<HH", cfg, 0x00, vendor, device)
    struct.pack_into("<H", cfg, 0x04, 0x0002)  # Memory Space Enable
    cfg[0x34] = 0x60                           # Capabilities pointer
    cfg[0x60] = 0x10                           # PCI Express Capability ID
    cfg[0x61] = 0x00                           # Next cap = none
    struct.pack_into("<I", cfg, 0x60 + 0x2C, lnkcap2 & 0xFFFFFFFF)
    return bytes(cfg)


class SimulatedGA100PCIe(MMIOBus):
    """Simulated GA100 BAR0 MMIO register file, OTP fuse array, and PCIe config space.

    Accurately models GA100 fuse-controller hardware physics:
      - 4-byte alignment, unsigned 32-bit value checks, and DEBUGCTRL write guard
      - EN_SW_OVERRIDE sticks only when DSOV == 0
      - WDATA_WR_SECURE opens/closes PLM_F4 only when DSOV == 0 and EN_SW_OVERRIDE == 1
      - FUSEWDATA latches only when PLM_F4 == 0xFFFFFFFF
      - CMD_READ latches rows[FUSEADDR] into FUSEDATA
      - CMD_SENSE_CTRL sets EFP=1, SBFE=1, RESENSE_DISABLE=1 while preserving DSOV=0
      - option shadows listed in ``unsensed_option_regs`` read 0 until a successful
        CMD_SENSE_CTRL: in a real Goldilocks frame the glitch leaves them unsensed
        (cmp170hx-8gb-vfi-tools SWEET_SPOT.md "the sentinel trap"); fuse ROWS read via
        CMD_READ are unaffected
      - CMD_PROGRAM performs OTP 0->1 bitwise OR into rows[FUSEADDR] only when armed
    """

    def __init__(
        self,
        *,
        rows: dict[int, int] | None = None,
        registers: dict[int, int] | None = None,
        goldilocks: bool = True,
        lnkcap2: int = 0x06,
        unsensed_option_regs: Iterable[int] = (),
    ) -> None:
        self.rows: dict[int, int] = {i: 0 for i in range(TOTAL_FUSE_ROWS)}
        # Stored values are the cold-boot truth; reads return 0 until SENSE_CTRL senses them.
        self.unsensed: set[int] = {int(a) for a in unsensed_option_regs}
        if rows:
            self.rows.update({int(k): int(v) & 0xFFFFFFFF for k, v in rows.items()})
        self.regs: dict[int, int] = {
            REG_PMC_BOOT_0: 0x170000A1,
            REG_FUSECTRL: 0xE0040000,
            REG_FUSEADDR: 0x00000000,
            REG_FUSEDATA: 0x00000000,
            REG_FUSEWDATA: 0x00000000,
            REG_EN_SW_OVERRIDE: 0x00000000,
            REG_IFF_RECORD: 0x00000000,
            REG_DEBUGCTRL: 0x00000000,
            REG_CRC_STATUS: 0x00000055,
            REG_EFP_STATUS: 0x00000000 if goldilocks else 0x00000001,
            REG_DFP_STATUS: 0x00000000,
            REG_DSOV_STATUS: 0x00000000 if goldilocks else 0x00000001,
            REG_PLM_F4: 0x00000000,  # locked until WDATA_WR_SECURE=0
            REG_PLM_F8: 0xFFFFFFFF if goldilocks else 0x00000000,
            REG_PLM_FC: 0xFFFFFFFF if goldilocks else 0x00000000,
            REG_WDATA_WR_SECURE: 0x00000001,
            REG_CTRL_WR_SECURE: 0x00000000,
            REG_RESENSE_DISABLE: 0x00000000 if goldilocks else 0x00000001,
            REG_SBFE_SHADOW: 0x00000000 if goldilocks else 0x00000001,
        }
        if registers:
            self.regs.update({int(k): int(v) & 0xFFFFFFFF for k, v in registers.items()})
        self.pci_config: bytes = build_pcie_config_space(lnkcap2=lnkcap2)
        self.writes: list[tuple[int, int]] = []
        self.reads: list[int] = []
        self.sense_calls: int = 0
        self.program_calls: int = 0
        self.poison_on_sense: bool = False
        self.drop_plm_f8_on_sense: bool = False
        self.lose_window_on_sense: bool = False

    def _validate_offset(self, offset: int) -> None:
        if isinstance(offset, bool) or not isinstance(offset, int) or offset < 0 or (offset & 3):
            raise BurnError(f"MMIO offset 0x{offset:x} is not 4-byte aligned")

    def read32(self, offset: int) -> int:
        self._validate_offset(offset)
        self.reads.append(offset)
        if offset in self.unsensed:
            return 0
        return self.regs.get(offset, 0)

    def write32(self, offset: int, value: int, *, allow_debugctrl: bool = False) -> None:
        self._validate_offset(offset)
        if isinstance(value, bool) or not isinstance(value, int) or not (0 <= value <= 0xFFFFFFFF):
            raise BurnError(f"MMIO write value out of unsigned 32-bit range: {value!r}")
        if offset == REG_DEBUGCTRL and not allow_debugctrl:
            raise BurnError("DEBUGCTRL blocked")
        self.writes.append((offset, value))
        if offset == REG_EN_SW_OVERRIDE:
            if self.regs[REG_DSOV_STATUS] == 0:
                self.regs[offset] = value & 1
            return
        if offset == REG_WDATA_WR_SECURE:
            if self.regs[REG_DSOV_STATUS] == 0 and self.regs[REG_EN_SW_OVERRIDE] == 1:
                self.regs[offset] = value & 1
                self.regs[REG_PLM_F4] = 0xFFFFFFFF if (value & 1) == 0 else 0x00000000
            return
        if offset == REG_SBFE_SHADOW:
            if self.regs[REG_DSOV_STATUS] == 0 and self.regs[REG_EN_SW_OVERRIDE] == 1:
                self.regs[offset] = value & 1
            return
        if offset == REG_FUSEWDATA:
            if self.regs[REG_PLM_F4] == 0xFFFFFFFF:
                self.regs[offset] = value & 0xFFFFFFFF
            return
        if offset == REG_FUSECTRL:
            cmd = value & 0x1F
            if cmd == CMD_IDLE:
                return
            if cmd == CMD_READ:
                row = self.regs[REG_FUSEADDR]
                self.regs[REG_FUSEDATA] = self.rows.get(row, 0)
                return
            if cmd == CMD_SENSE_CTRL:
                self.sense_calls += 1
                if self.poison_on_sense:
                    self.regs[REG_FUSECTRL] = 0xBADF510E
                    return
                if self.drop_plm_f8_on_sense:
                    self.regs[REG_PLM_F8] = 0xFFFFFFFE
                    return
                if self.lose_window_on_sense:
                    self.regs[REG_DSOV_STATUS] = 1
                    self.regs[REG_EFP_STATUS] = 1
                    self.regs[REG_SBFE_SHADOW] = 1
                    self.regs[REG_RESENSE_DISABLE] = 1
                    self.unsensed.clear()
                    return
                self.regs[REG_EFP_STATUS] = 1
                self.regs[REG_SBFE_SHADOW] = 1
                self.regs[REG_RESENSE_DISABLE] = 1
                self.unsensed.clear()  # SENSE_CTRL senses the option shadows (DSOV stays 0)
                return
            if cmd == CMD_PROGRAM:
                self.program_calls += 1
                row = self.regs[REG_FUSEADDR]
                if (
                    self.regs[REG_EFP_STATUS] == 1
                    and self.regs[REG_SBFE_SHADOW] == 0
                    and self.regs[REG_PLM_F4] == 0xFFFFFFFF
                    and self.regs[REG_DEBUGCTRL] == 0
                ):
                    self.rows[row] = self.rows.get(row, 0) | self.regs[REG_FUSEWDATA]
                return
        self.regs[offset] = value & 0xFFFFFFFF


class SimulatedGA100Adapter(FuseReader, FuseWriter):
    """Full simulated PCIe adapter running the real ``GA100FuseController`` HAL.

    Every ``die_row``, ``fuse_row``, ``health``, ``active_sense_readonly``, and
    ``write_one_record`` call executes through ``GA100FuseController`` ->
    ``TracingMMIOBus`` -> ``SimulatedGA100PCIe``.
    """

    simulation = True
    write_enabled = False
    writer_verified = False

    def __init__(
        self,
        *,
        pci_id: str = SKU_CMP170HX_8GB,
        die: dict[int, int] | None = None,
        rows: dict[int, int] | None = None,
        fields: dict[str, int] | None = None,
        health: Health | None = None,
        host: Host | None = None,
        registers: dict[int, int] | None = None,
        lnkcap2: int = 0x06,
    ) -> None:
        self._pci_id = pci_id
        die_map = dict(die) if die is not None else {i: 0x1000 + i for i in DIE_ID_ROWS}
        merged_rows = {**die_map, **(rows or {})}
        merged_regs: dict[int, int] = dict(registers or {})
        self._fields = dict(fields or {})
        for fname, val in self._fields.items():
            key = fname.strip().upper()
            if key in OPTION_REGS:
                merged_regs[OPTION_REGS[key]] = val & 0xFFFFFFFF
        if health is not None:
            merged_regs[REG_FUSECTRL] = health.fusectrl
            merged_regs[REG_DSOV_STATUS] = health.dsov
            merged_regs[REG_CRC_STATUS] = health.crc
            merged_regs[REG_PLM_FC] = health.plm
            merged_regs[REG_PLM_F8] = health.plm_f8
            merged_regs[REG_EN_SW_OVERRIDE] = health.en_sw
            merged_regs[REG_DEBUGCTRL] = health.debugctrl
            if health.efp is not None:
                merged_regs[REG_EFP_STATUS] = health.efp
            if health.dfp is not None:
                merged_regs[REG_DFP_STATUS] = health.dfp
            if health.plm_f4 is not None:
                merged_regs[REG_PLM_F4] = health.plm_f4
            if health.sbfe is not None:
                merged_regs[REG_SBFE_SHADOW] = health.sbfe
            if health.wdata_wr_secure is not None:
                merged_regs[REG_WDATA_WR_SECURE] = health.wdata_wr_secure
            if health.resense_disable is not None:
                merged_regs[REG_RESENSE_DISABLE] = health.resense_disable
        eff_lnkcap2 = self._fields.get("LnkCap2", lnkcap2)
        goldilocks = health is None or health.dsov == 0
        dsov = merged_regs.get(REG_DSOV_STATUS, 0 if goldilocks else 1)
        efp = merged_regs.get(REG_EFP_STATUS, 0 if goldilocks else 1)
        # A pre-SENSE Goldilocks frame (DSOV=0, EFP=0) has unsensed option shadows.
        unsensed = set(OPTION_REGS.values()) if dsov == 0 and efp == 0 else set()
        self.pcie = SimulatedGA100PCIe(
            rows=merged_rows,
            registers=merged_regs,
            goldilocks=goldilocks,
            lnkcap2=eff_lnkcap2,
            unsensed_option_regs=unsensed,
        )
        self.bus = TracingMMIOBus(self.pcie)
        self.controller = GA100FuseController(self.bus, read_only=False, sleep=lambda _: None)
        self.machine = host or Host("pci-stub", False, False, "[none]", True, "sim-pcie-boot-1")

    def pci_id(self) -> str:
        return self._pci_id

    def die_row(self, index: int) -> int:
        if index not in DIE_ID_ROWS:
            raise BurnError(f"die_row index {index} outside 8..15")
        return self.controller.read_row(index)

    def fuse_row(self, index: int) -> int:
        return self.controller.read_row(index)

    def register(self, address: int) -> int:
        return self.controller.rd(address)

    def field(self, name: str) -> int:
        if name == "LnkCap2":
            return parse_pcie_lnkcap2(self.pcie.pci_config)
        if name == "SM_COUNT":
            gpc = self.controller.rd(OPTION_REGS["GPC_DISABLE"])
            tpcs = [self.controller.rd(OPTION_REGS[f"TPC_GPC{i}_DISABLE"]) for i in range(TOTAL_GPC)]
            return compute_sm_count(gpc, tpcs)
        key = name.strip().upper()
        if key in OPTION_REGS:
            return self.controller.rd(OPTION_REGS[key])
        if name in self._fields:
            return self._fields[name]
        raise BurnError(f"unknown simulated GA100 field {name!r}")

    def health(self) -> Health:
        return self.controller.read_health_registers()

    def host(self) -> Host:
        return Host(**self.machine.serializable())

    def active_sense_readonly(self) -> None:
        self.controller.sense_ctrl()

    def write_one_record(self, row: int, word: int) -> None:
        self.controller.program_row(row, word)

    def to_snapshot_dict(self) -> dict:
        """Serialize current simulated PCIe state into the standard fake-snapshot JSON schema."""
        die_rows = {i: self.pcie.rows.get(i, 0) for i in DIE_ID_ROWS}
        ff_rows = {r: v for r, v in sorted(self.pcie.rows.items()) if r not in DIE_ID_ROWS and (v != 0 or 222 <= r <= 486)}
        return {
            "pci_id": self._pci_id,
            "die_rows": die_rows,
            "fields": dict(self._fields),
            "rows": ff_rows,
            "health": self.health().serializable(),
            "host": self.host().serializable(),
            "registers": {hex(k): v for k, v in sorted(self.pcie.regs.items())},
        }


def sim_pcie_from_file(path) -> SimulatedGA100Adapter:
    """Load a mode-0600 JSON snapshot into a HAL-backed ``SimulatedGA100Adapter``."""
    import json
    from .model import require_private_file, u32

    p = require_private_file(path, "simulated PCIe snapshot")
    try:
        data = json.loads(p.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise BurnError(f"invalid JSON in simulated PCIe snapshot {p}: {exc}") from exc
    if not isinstance(data, dict):
        raise BurnError("simulated PCIe snapshot root must be a JSON object")
    try:
        health_raw = data["health"]
        health_kwargs = {
            k: (None if v is None else u32(v, f"health.{k}"))
            for k, v in health_raw.items()
        }
        return SimulatedGA100Adapter(
            pci_id=str(data["pci_id"]),
            die={int(k): u32(v, f"die_rows.{k}") for k, v in data["die_rows"].items()},
            fields={str(k): u32(v, f"fields.{k}") for k, v in data["fields"].items()},
            rows={int(k): u32(v, f"rows.{k}") for k, v in data["rows"].items()},
            health=Health(**health_kwargs),
            host=Host(**data["host"]),
            registers={
                int(k, 0): u32(v, f"registers.{k}")
                for k, v in data.get("registers", {}).items()
            },
        )
    except (KeyError, TypeError, ValueError) as exc:
        raise BurnError(f"malformed simulated PCIe snapshot {p}: {exc}") from exc


def trace_hal_program_sequence(
    row: int,
    word: int,
    health: Health,
    *,
    skip_sense: bool = False,
) -> tuple[list[PCIeTransaction], list[PCIeTransaction], list[PCIeTransaction]]:
    """Dry-run ``GA100FuseController`` on an ephemeral simulated PCIe bus to capture exact BAR0 writes.

    Returns ``(sense_writes, arm_and_program_writes, readback_writes)`` directly from the HAL so
    previews can never drift out of sync with ``GA100FuseController``.
    """
    already_sensed = health.efp == 1
    sim_regs: dict[int, int] = {
        REG_FUSECTRL: 0xE0040000,
        REG_DSOV_STATUS: 0,
        REG_CRC_STATUS: 0x55,
        REG_PLM_FC: 0xFFFFFFFF,
        REG_PLM_F8: 0xFFFFFFFF,
        REG_DEBUGCTRL: 0,
        REG_DFP_STATUS: 0,
        REG_EFP_STATUS: 1 if (already_sensed or skip_sense) else 0,
        REG_RESENSE_DISABLE: 1 if already_sensed else 0,
        REG_SBFE_SHADOW: 0 if (already_sensed and health.sbfe == 0) else 1,
        REG_EN_SW_OVERRIDE: 1 if already_sensed else 0,
        REG_WDATA_WR_SECURE: 0 if already_sensed else 1,
        REG_PLM_F4: 0xFFFFFFFF if already_sensed else 0x00000000,
    }
    pcie = SimulatedGA100PCIe(rows={row: 0}, registers=sim_regs, goldilocks=True)
    bus = TracingMMIOBus(pcie)
    ctl = GA100FuseController(bus, read_only=False, sleep=lambda _: None)

    sense_writes: list[PCIeTransaction] = []
    if not already_sensed and not skip_sense:
        ctl.sense_ctrl()
        sense_writes = bus.writes()
        bus.clear()

    ctl.program_row(row, word)
    # program_row calls arm() -> read_row(blank check) -> stage + CMD_PROGRAM + relatch -> read_row(verify).
    all_prog_writes = bus.writes()

    # Split at the CMD_PROGRAM + post-program relatch (FUSEWDATA=0) vs final CMD_READ readback.
    cmd_prog_idx = next(
        i for i, tx in enumerate(all_prog_writes)
        if tx.offset == REG_FUSECTRL and tx.value == CMD_PROGRAM
    )
    # Include the two relatch writes immediately following CMD_PROGRAM (FUSEADDR restore + FUSEWDATA=0).
    relatch_end = min(len(all_prog_writes), cmd_prog_idx + 3)
    arm_and_program_writes = all_prog_writes[:relatch_end]
    readback_writes = all_prog_writes[relatch_end:]
    return sense_writes, arm_and_program_writes, readback_writes
